-- Migration 076 for Postgres, the twin of migrations/076-channels-keep-docs.sql: linked markdown
-- docs in each channel, their kept versions, and the [[links]] between them.
CREATE TABLE "docs" (
	seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	team_id text COLLATE "C" NOT NULL DEFAULT 'home',
	id text COLLATE "C" NOT NULL UNIQUE,
	project_id text COLLATE "C" NOT NULL,
	title text COLLATE "C" NOT NULL,
	title_key text COLLATE "C" NOT NULL,
	body text COLLATE "C" NOT NULL,
	version bigint NOT NULL,
	created_by text COLLATE "C" NOT NULL,
	created_at bigint NOT NULL,
	updated_by text COLLATE "C" NOT NULL,
	updated_at bigint NOT NULL,
	deleted_at bigint
);

CREATE UNIQUE INDEX docs_title ON docs (team_id, project_id, title_key);
CREATE INDEX docs_project ON docs (team_id, project_id, updated_at);

CREATE TABLE "doc_versions" (
	seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	team_id text COLLATE "C" NOT NULL DEFAULT 'home',
	id text COLLATE "C" NOT NULL UNIQUE,
	doc_id text COLLATE "C" NOT NULL,
	version bigint NOT NULL,
	title text COLLATE "C" NOT NULL,
	body text COLLATE "C" NOT NULL,
	saved_by text COLLATE "C" NOT NULL,
	saved_at bigint NOT NULL,
	restored_from bigint
);

CREATE UNIQUE INDEX doc_versions_doc ON doc_versions (team_id, doc_id, version);

CREATE TABLE "doc_links" (
	seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	team_id text COLLATE "C" NOT NULL DEFAULT 'home',
	doc_id text COLLATE "C" NOT NULL,
	project_id text COLLATE "C" NOT NULL,
	target_key text COLLATE "C" NOT NULL
);

CREATE UNIQUE INDEX doc_links_pair ON doc_links (team_id, doc_id, target_key);
CREATE INDEX doc_links_target ON doc_links (team_id, project_id, target_key);
CREATE POLICY team_rows ON "docs" USING (team_id = current_setting('app.team', true) OR current_setting('app.team', true) = '*');
CREATE POLICY team_rows ON "doc_versions" USING (team_id = current_setting('app.team', true) OR current_setting('app.team', true) = '*');
CREATE POLICY team_rows ON "doc_links" USING (team_id = current_setting('app.team', true) OR current_setting('app.team', true) = '*');
-- Where row security is already on (any table here forced), switch it on for these tables too, as
-- 072 and 074 do; the server's start does the same from TeamTables.ALL.
DO 'DECLARE t text; BEGIN
	IF EXISTS (SELECT 1 FROM pg_class WHERE relnamespace = current_schema()::regnamespace AND relkind = ''r'' AND relforcerowsecurity) THEN
		FOREACH t IN ARRAY ARRAY[''docs'', ''doc_versions'', ''doc_links''] LOOP
			EXECUTE format(''ALTER TABLE %I ENABLE ROW LEVEL SECURITY'', t);
			EXECUTE format(''ALTER TABLE %I FORCE ROW LEVEL SECURITY'', t);
		END LOOP;
	END IF;
END';
