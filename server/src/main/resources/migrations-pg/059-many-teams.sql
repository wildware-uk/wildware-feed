-- Migration 059 for Postgres, the twin of migrations/059-many-teams.sql. It also drops the last
-- server-wide name rules (apps, embed types, settings), now that the code names the per-team ones
-- migration 058 made, and gives auth_codes the row-security policy every team table has.
ALTER TABLE "teams" ADD COLUMN external_ref text COLLATE "C";
ALTER TABLE "teams" ADD COLUMN seat_limit bigint;
ALTER TABLE "teams" ADD COLUMN storage_limit bigint;
ALTER TABLE "teams" ADD COLUMN suspended_at bigint;
ALTER TABLE "teams" ADD COLUMN suspended_reason text COLLATE "C";
ALTER TABLE "teams" ADD COLUMN suspended_message text COLLATE "C";
ALTER TABLE "teams" ADD COLUMN state text COLLATE "C" NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'deleting', 'deleted'));
ALTER TABLE "teams" ADD COLUMN deleted_at bigint;
ALTER TABLE "teams" ADD COLUMN updated_at bigint NOT NULL DEFAULT 0;
CREATE INDEX teams_external_ref ON teams (external_ref);

ALTER TABLE "users" ADD COLUMN email_verified_at bigint;

CREATE TABLE "auth_codes" (
	seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id text COLLATE "C" NOT NULL UNIQUE,
	team_id text COLLATE "C" NOT NULL,
	kind text COLLATE "C" NOT NULL CHECK (kind IN ('setup', 'ticket')),
	code_hash text COLLATE "C" NOT NULL UNIQUE,
	membership_id text COLLATE "C" NOT NULL,
	created_at bigint NOT NULL,
	expires_at bigint NOT NULL
);

ALTER TABLE "auth_codes" ADD FOREIGN KEY (team_id) REFERENCES teams (id) DEFERRABLE INITIALLY IMMEDIATE;
ALTER TABLE "auth_codes" ADD FOREIGN KEY (membership_id) REFERENCES memberships (id) DEFERRABLE INITIALLY IMMEDIATE;
CREATE INDEX auth_codes_membership ON auth_codes (team_id, membership_id, kind);
CREATE POLICY team_rows ON "auth_codes" USING (team_id = current_setting('app.team', true) OR current_setting('app.team', true) = '*');

CREATE TABLE "admin_requests" (
	seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	idem_key text COLLATE "C" NOT NULL UNIQUE,
	fingerprint text COLLATE "C" NOT NULL,
	state text COLLATE "C" NOT NULL CHECK (state IN ('running', 'done')),
	status bigint,
	body text COLLATE "C",
	created_at bigint NOT NULL
);

ALTER TABLE "apps" DROP CONSTRAINT apps_uri_key;
ALTER TABLE "embed_types" DROP CONSTRAINT embed_types_slug_key;
ALTER TABLE "server_settings" DROP CONSTRAINT server_settings_key_key;
