-- Migration 067 for Postgres, the twin of migrations/067-feedback.sql: feedback and feature
-- requests, a team's own rows only (row security), and the media sent with them.
CREATE TABLE "feedback" (
	seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	team_id text COLLATE "C" NOT NULL DEFAULT 'home',
	id text COLLATE "C" NOT NULL UNIQUE,
	kind text COLLATE "C" NOT NULL CHECK (kind IN ('feedback', 'feature_request')),
	area text COLLATE "C",
	title text COLLATE "C" NOT NULL,
	body text COLLATE "C" NOT NULL,
	author_kind text COLLATE "C" NOT NULL CHECK (author_kind IN ('person', 'agent')),
	author_id text COLLATE "C" NOT NULL,
	author_name text COLLATE "C" NOT NULL,
	card_kind text COLLATE "C" CHECK (card_kind IN ('update', 'message', 'request')),
	card_id text COLLATE "C",
	status text COLLATE "C" NOT NULL CHECK (status IN ('pending', 'discarded', 'sent', 'saved')),
	request_id text COLLATE "C",
	approved_by text COLLATE "C",
	sentry_event_id text COLLATE "C",
	created_at bigint NOT NULL,
	sent_at bigint,
	updated_at bigint NOT NULL
);

CREATE INDEX feedback_team ON feedback (team_id, seq);
CREATE INDEX feedback_author ON feedback (team_id, author_kind, author_id, created_at);
CREATE INDEX feedback_request ON feedback (team_id, request_id);
CREATE POLICY team_rows ON "feedback" USING (team_id = current_setting('app.team', true) OR current_setting('app.team', true) = '*');

ALTER TABLE "media" ADD COLUMN feedback_id text COLLATE "C";
