ALTER TABLE "projects" ADD COLUMN private bigint NOT NULL DEFAULT 0 CHECK (private IN (0, 1));
ALTER TABLE "project_groups" ADD COLUMN private bigint NOT NULL DEFAULT 0 CHECK (private IN (0, 1));

CREATE TABLE "channel_access" (
	seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	team_id text COLLATE "C" NOT NULL DEFAULT 'home',
	id text COLLATE "C" NOT NULL UNIQUE,
	target_kind text COLLATE "C" NOT NULL CHECK (target_kind IN ('channel', 'group')),
	target_id text COLLATE "C" NOT NULL,
	principal text COLLATE "C" NOT NULL,
	level text COLLATE "C" NOT NULL CHECK (level IN ('none', 'read', 'post', 'manage')),
	created_at bigint NOT NULL,
	updated_at bigint NOT NULL,
	updated_by text COLLATE "C" NOT NULL
);

CREATE UNIQUE INDEX channel_access_target ON channel_access (team_id, target_kind, target_id, principal);
CREATE INDEX channel_access_principal ON channel_access (team_id, principal);
CREATE POLICY team_rows ON "channel_access" USING (team_id = current_setting('app.team', true) OR current_setting('app.team', true) = '*');

CREATE TABLE "access_audit" (
	seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	team_id text COLLATE "C" NOT NULL DEFAULT 'home',
	id text COLLATE "C" NOT NULL UNIQUE,
	at bigint NOT NULL,
	actor text COLLATE "C" NOT NULL,
	target_kind text COLLATE "C" NOT NULL CHECK (target_kind IN ('channel', 'group')),
	target_id text COLLATE "C" NOT NULL,
	target_name text COLLATE "C" NOT NULL,
	principal text COLLATE "C",
	change text COLLATE "C" NOT NULL CHECK (change IN ('level', 'private')),
	old_value text COLLATE "C",
	new_value text COLLATE "C"
);

CREATE INDEX access_audit_at ON access_audit (team_id, seq);
CREATE POLICY team_rows ON "access_audit" USING (team_id = current_setting('app.team', true) OR current_setting('app.team', true) = '*');
