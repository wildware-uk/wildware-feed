-- Migration 071 for Postgres, the twin of migrations/071-people-delete-their-account.sql: when an
-- account was deleted, and the audit of deletions (not a team's table, so no row security).
ALTER TABLE "users" ADD COLUMN deleted_at bigint;

CREATE TABLE "account_deletions" (
	seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	id text COLLATE "C" NOT NULL UNIQUE,
	account_id text COLLATE "C" NOT NULL,
	email_hash text COLLATE "C",
	teams text COLLATE "C" NOT NULL,
	deleted_at bigint NOT NULL
);

CREATE INDEX account_deletions_at ON account_deletions (deleted_at, seq);
