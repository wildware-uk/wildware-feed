-- Migration 080 for Postgres, the twin of migrations/080-github-prs.sql: the GitHub App
-- installations each team linked, and the pull requests linked to cards.
CREATE TABLE "github_installations" (
	seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	team_id text COLLATE "C" NOT NULL DEFAULT 'home',
	id text COLLATE "C" NOT NULL UNIQUE,
	installation_id bigint NOT NULL,
	account text COLLATE "C" NOT NULL,
	added_by text COLLATE "C" NOT NULL,
	added_at bigint NOT NULL
);

CREATE UNIQUE INDEX github_installations_team ON github_installations (team_id, installation_id);
CREATE INDEX github_installations_installation ON github_installations (installation_id);

CREATE TABLE "card_prs" (
	seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	team_id text COLLATE "C" NOT NULL DEFAULT 'home',
	id text COLLATE "C" NOT NULL UNIQUE,
	update_id text COLLATE "C" NOT NULL,
	repo text COLLATE "C" NOT NULL,
	number bigint NOT NULL,
	url text COLLATE "C" NOT NULL,
	owner text COLLATE "C" NOT NULL,
	linked_at bigint NOT NULL,
	title text COLLATE "C",
	state text COLLATE "C",
	head_sha text COLLATE "C",
	checks text COLLATE "C" NOT NULL DEFAULT '{}',
	ci text COLLATE "C" NOT NULL DEFAULT 'none',
	reviews text COLLATE "C" NOT NULL DEFAULT '{}',
	review text COLLATE "C" NOT NULL DEFAULT 'none',
	alerted_sha text COLLATE "C",
	red_open bigint NOT NULL DEFAULT 0,
	review_alerted bigint,
	updated_at bigint NOT NULL
);

CREATE UNIQUE INDEX card_prs_card ON card_prs (team_id, update_id, repo, number);
CREATE INDEX card_prs_pr ON card_prs (team_id, repo, number);
CREATE POLICY team_rows ON "github_installations" USING (team_id = current_setting('app.team', true) OR current_setting('app.team', true) = '*');
CREATE POLICY team_rows ON "card_prs" USING (team_id = current_setting('app.team', true) OR current_setting('app.team', true) = '*');
-- Where row security is already on (any table here forced), switch it on for these tables too, as
-- 076 does; the server's start does the same from TeamTables.ALL.
DO 'DECLARE t text; BEGIN
	IF EXISTS (SELECT 1 FROM pg_class WHERE relnamespace = current_schema()::regnamespace AND relkind = ''r'' AND relforcerowsecurity) THEN
		FOREACH t IN ARRAY ARRAY[''github_installations'', ''card_prs''] LOOP
			EXECUTE format(''ALTER TABLE %I ENABLE ROW LEVEL SECURITY'', t);
			EXECUTE format(''ALTER TABLE %I FORCE ROW LEVEL SECURITY'', t);
		END LOOP;
	END IF;
END';
