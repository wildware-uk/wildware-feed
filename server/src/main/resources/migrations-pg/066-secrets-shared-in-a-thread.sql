-- Migration 066 for Postgres, the twin of migrations/066-secrets-shared-in-a-thread.sql: a secret
-- an agent attached to a post, by name, with no value and no link to the secret's row.
CREATE TABLE "card_secrets" (
	seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	team_id text COLLATE "C" NOT NULL DEFAULT 'home',
	card_kind text COLLATE "C" NOT NULL CHECK (card_kind IN ('update', 'message')),
	card_id text COLLATE "C" NOT NULL,
	secret_id text COLLATE "C" NOT NULL,
	secret_name text COLLATE "C" NOT NULL,
	agent_id text COLLATE "C" NOT NULL,
	created_at bigint NOT NULL
);

CREATE UNIQUE INDEX card_secrets_card ON card_secrets (team_id, card_kind, card_id, secret_name);
CREATE POLICY team_rows ON "card_secrets" USING (team_id = current_setting('app.team', true) OR current_setting('app.team', true) = '*');
