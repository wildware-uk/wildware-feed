#!/usr/bin/env python3
"""
Writes the Postgres baseline migration from the SQLite schema, mechanically, so the two can't drift.

Input: a JSON dump of a fresh SQLite database's sqlite_master (server/src/test/resources/ts-schema.json,
which DatabaseTest checks against the TS server). Output: a Postgres script with the same tables,
columns, defaults, checks, keys and indexes:

- `seq INTEGER PRIMARY KEY AUTOINCREMENT` -> `seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`
- INTEGER -> bigint (flags stay 0/1 integers, as the code reads them)
- TEXT -> text COLLATE "C" (byte order, as SQLite's BINARY sorts)
- inline REFERENCES -> ALTER TABLE ... ADD FOREIGN KEY ... DEFERRABLE INITIALLY IMMEDIATE, after every
  table exists (some tables point at each other; deferrable lets a bulk copy load in any order)
- STRICT and SQL comments dropped; schema_migrations is left to the migration runner.

Seed rows (the built-in embed types) come from a fresh database the TS server made, copied as
INSERTs with each identity moved past them.

  sqlite_to_pg.py ts-schema.json fresh.db > 047-baseline.sql
"""
import json
import re
import sqlite3
import sys


def strip_comments(sql):
    return re.sub(r"--[^\n]*", "", sql)


def split_top(body):
    """Split on commas outside parentheses and quotes."""
    parts, depth, quote, cur = [], 0, None, []
    for ch in body:
        if quote:
            cur.append(ch)
            if ch == quote:
                quote = None
            continue
        if ch in "'\"":
            quote = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        elif ch == "," and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
            continue
        cur.append(ch)
    if "".join(cur).strip():
        parts.append("".join(cur).strip())
    return parts


REF = re.compile(r"\s+REFERENCES\s+\"?(\w+)\"?\s*\((\w+)\)((?:\s+ON\s+DELETE\s+(?:CASCADE|SET NULL|RESTRICT|NO ACTION))?)", re.I)
CONSTRAINT_WORDS = ("PRIMARY", "UNIQUE", "CHECK", "FOREIGN", "CONSTRAINT")


def translate(name, sql):
    sql = strip_comments(sql).strip()
    head, body = sql.split("(", 1)
    body = body.rsplit(")", 1)[0]
    columns, fks = [], []
    for item in split_top(body):
        item = " ".join(item.split())
        if item.upper().startswith(CONSTRAINT_WORDS):
            if item.upper().startswith("FOREIGN"):
                raise SystemExit(f"{name}: table-level FOREIGN KEY not handled")
            columns.append(item)
            continue
        col, rest = item.split(" ", 1)
        m = REF.search(rest)
        if m:
            fks.append(f'ALTER TABLE "{name}" ADD FOREIGN KEY ({col}) REFERENCES {m.group(1)} ({m.group(2)}){m.group(3)} DEFERRABLE INITIALLY IMMEDIATE;')
            rest = REF.sub("", rest)
        if re.match(r"INTEGER PRIMARY KEY AUTOINCREMENT\b", rest, re.I):
            rest = "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" + rest[len("INTEGER PRIMARY KEY AUTOINCREMENT"):]
        elif rest.upper().startswith("INTEGER"):
            rest = "bigint" + rest[len("INTEGER"):]
        elif rest.upper().startswith("TEXT"):
            rest = 'text COLLATE "C"' + rest[len("TEXT"):]
        else:
            raise SystemExit(f"{name}.{col}: type not handled: {rest}")
        columns.append(f"{col} {rest}")
    table = f'CREATE TABLE "{name}" (\n\t' + ",\n\t".join(columns) + "\n);"
    return table, fks


def literal(v):
    if v is None:
        return "NULL"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return "'" + v.replace("'", "''") + "'"
    raise SystemExit(f"value not handled: {type(v)}")


def seeds(db_path, tables):
    c = sqlite3.connect(db_path)
    out = []
    for t in tables:
        name = t["name"]
        cols = [r[1] for r in c.execute(f'PRAGMA table_info("{name}")')]
        rows = c.execute(f'SELECT * FROM "{name}" ORDER BY rowid').fetchall()
        if not rows:
            continue
        for r in rows:
            out.append(f'INSERT INTO "{name}" ({", ".join(cols)}) VALUES ({", ".join(literal(v) for v in r)});')
        if "seq" in cols:
            out.append(f"SELECT setval(pg_get_serial_sequence('\"{name}\"', 'seq'), (SELECT max(seq) FROM \"{name}\"));")
    return out


def main(path, db_path):
    rows = json.load(open(path))
    tables = [r for r in rows if r["type"] == "table" and r["name"] != "schema_migrations"]
    indexes = [r for r in rows if r["type"] == "index" and r["sql"]]
    out = ["-- Generated by server/tools/sqlite_to_pg.py from the SQLite schema after migration 047.", ""]
    all_fks = []
    for t in tables:
        created, fks = translate(t["name"], t["sql"])
        out += [created, ""]
        all_fks += fks
    out += all_fks + [""]
    for i in sorted(indexes, key=lambda r: r["name"]):
        out += [" ".join(strip_comments(i["sql"]).split()) + ";", ""]
    out += seeds(db_path, tables) + [""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
